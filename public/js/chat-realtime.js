/*
|--------------------------------------------------------------------------
| Хранилище подключенных каналов
|--------------------------------------------------------------------------
*/

let chatChannels = {};
let typingTimeouts = {};

/*
|--------------------------------------------------------------------------
| Подключение к каналу чата
|--------------------------------------------------------------------------
*/

function connectToChat(chatId) {

    // Если уже подключен — повторно не подключаем
    if (chatChannels[chatId]) {
        return;
    }

    /*
    |--------------------------------------------------------------------------
    | Подключаем private-канал
    |--------------------------------------------------------------------------
    */

    chatChannels[chatId] = window.Echo.private(`chat.${chatId}`);

    /*
    |--------------------------------------------------------------------------
    | Слушаем whisper typing
    |--------------------------------------------------------------------------
    */

    chatChannels[chatId].listenForWhisper('typing', (e) => {
        handleTyping(e);
    });
}

/*
|--------------------------------------------------------------------------
| Отправка события "печатает"
|--------------------------------------------------------------------------
*/

function sendTyping(chatId, userId) {

    // Канал не найден
    if (!chatChannels[chatId]) {
        console.log('Channel not connected:', chatId);
        return;
    }

    chatChannels[chatId].whisper('typing', {
        chat_id: chatId,
        user_id: userId
    });
}

/*
|--------------------------------------------------------------------------
| Очистка typing timeout
|--------------------------------------------------------------------------
*/

function stopTyping(chatId) {

    if (typingTimeouts[chatId]) {
        clearTimeout(typingTimeouts[chatId]);
        delete typingTimeouts[chatId];
    }
}

/*
|--------------------------------------------------------------------------
| Глобальный объект
|--------------------------------------------------------------------------
*/

window.ChatRealtime = {
    connectToChat,
    sendTyping,
    stopTyping
};

/*
|--------------------------------------------------------------------------
| Визуализация "печатает..."
|--------------------------------------------------------------------------
*/

function handleTyping(e) {

    const payload = e.data ?? e;
    const chatId = payload.chat_id;

    if (!chatId) {
        return;
    }

    /*
    |--------------------------------------------------------------------------
    | Ищем чат
    |--------------------------------------------------------------------------
    */

    const $chat = $('#' + chatId);

    if (!$chat.length) {
        console.log('Chat not found:', chatId);
        return;
    }

    const $typingText = $chat.find('.is_typing_text');

    /*
    |--------------------------------------------------------------------------
    | Сбрасываем предыдущий timeout
    |--------------------------------------------------------------------------
    */

    if (typingTimeouts[chatId]) {
        clearTimeout(typingTimeouts[chatId]);
    }

    /*
    |--------------------------------------------------------------------------
    | Если чат открыт — показываем верхний статус
    |--------------------------------------------------------------------------
    */

    if ($chat.hasClass('active')) {

        $('#typing-status')
            .stop(false, true)
            .show(300);
    }

    /*
    |--------------------------------------------------------------------------
    | Текст "печатает..."
    |--------------------------------------------------------------------------
    */

    $typingText.html(`
        <div style="position:absolute">
            Печатает
            <span class="dots">
                <span></span>
                <span></span>
                <span></span>
            </span>
        </div>
    `);

    /*
    |--------------------------------------------------------------------------
    | Автоочистка
    |--------------------------------------------------------------------------
    */

    typingTimeouts[chatId] = setTimeout(() => {

        if ($chat.hasClass('active')) {

            $('#typing-status')
                .stop(false, true)
                .hide(300);
        }

        $typingText.empty();

        delete typingTimeouts[chatId];

    }, 1500);
}
